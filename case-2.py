# Импортируем модуль для работы с абстрактными классами
from abc import ABC, abstractmethod


# -----------------------------------------------------------------------------
# БАЗОВЫЙ КЛАСС Employee (сотрудник)
# -----------------------------------------------------------------------------
class Employee(ABC):
    """
    Абстрактный базовый класс для всех сотрудников компании.
    Содержит общие атрибуты (имя, ID) и объявляет абстрактный метод
    calculate_salary(), который обязательно должны переопределить наследники.
    """

    def __init__(self, name: str, employee_id: int):
        """
        Конструктор (инициализатор) базового класса.
        Принимает имя сотрудника и его табельный номер.
        Сохраняет их в атрибуты экземпляра self.name и self.employee_id.
        """
        self.name = name               # Имя сотрудника (публичный атрибут)
        self.employee_id = employee_id # Уникальный идентификатор

    @abstractmethod
    def calculate_salary(self) -> float:
        """
        Абстрактный метод (декоратор @abstractmethod).
        Он объявлен, но не реализован в базовом классе.
        Все производные классы ОБЯЗАНЫ предоставить свою реализацию.
        Возвращает значение зарплаты (вещественное число).
        """
        pass  # Заглушка — реализация будет в наследниках

    def display(self) -> str:
        """
        Обычный (не абстрактный) метод, который может быть переопределён,
        но в базовом классе даёт общую информацию о сотруднике.
        Возвращает строку с именем и ID.
        """
        return f"Employee {self.name} (ID: {self.employee_id})"

    # Переопределяем специальный метод __str__ для удобного вывода в print()
    def __str__(self) -> str:
        """
        Специальный метод Python, который вызывается функциями str() и print().
        Если не переопределён, используется стандартный вывод типа <__main__.Employee ...>.
        Здесь мы возвращаем то же, что и display(), для удобства.
        """
        return self.display()


# -----------------------------------------------------------------------------
# ПРОИЗВОДНЫЙ КЛАСС Manager (менеджер) - наследник Employee
# -----------------------------------------------------------------------------
class Manager(Employee):
    """
    Класс Manager наследует все атрибуты и методы от Employee.
    Добавляет свои поля: базовый оклад (base_salary) и бонус (bonus).
    Переопределяет методы calculate_salary() и display().
    Также добавляет собственный метод conduct_meeting().
    """

    def __init__(self, name: str, employee_id: int, base_salary: float, bonus: float):
        """
        Конструктор производного класса.
        Сначала вызываем конструктор родительского класса через super(),
        чтобы инициализировать общие поля (name и employee_id).
        Затем добавляем свои специфические поля.
        """
        # super() возвращает объект родительского класса, чтобы мы могли вызвать его __init__
        super().__init__(name, employee_id)
        self.base_salary = base_salary   # Фиксированный оклад менеджера
        self.bonus = bonus               # Премия (может меняться)

    # Переопределяем абстрактный метод родителя
    def calculate_salary(self) -> float:
        """
        Реализация расчёта зарплаты для менеджера.
        Поскольку метод объявлен как @abstractmethod в Employee,
        мы ОБЯЗАНЫ предоставить его реализацию здесь.
        Зарплата менеджера = оклад + бонус.
        """
        return self.base_salary + self.bonus

    # Переопределяем метод display() для более конкретной информации
    def display(self) -> str:
        """
        Возвращает строку, специфичную для менеджера,
        включая размер его бонуса.
        """
        return f"Manager {self.name} (ID: {self.employee_id}), bonus = {self.bonus}"

    # Собственный метод, отсутствующий в базовом классе
    def conduct_meeting(self) -> str:
        """
        Метод, характерный только для менеджеров.
        Возвращает строку о проведении совещания.
        """
        return f"{self.name} организовывает встречи"


# -----------------------------------------------------------------------------
# ПРОИЗВОДНЫЙ КЛАСС Developer (разработчик) - наследник Employee
# -----------------------------------------------------------------------------
class Developer(Employee):
    """
    Класс Developer наследует Employee.
    Добавляет поля: почасовая ставка (hourly_rate) и количество отработанных часов.
    Переопределяет методы расчёта зарплаты и вывода.
    Добавляет метод write_code().
    """

    def __init__(self, name: str, employee_id: int, hourly_rate: float, hours_worked: float):
        """
        Конструктор разработчика.
        Как и в Manager, сначала вызываем конструктор базового класса,
        затем инициализируем свои поля.
        """
        super().__init__(name, employee_id)
        self.hourly_rate = hourly_rate   # Ставка за час работы
        self.hours_worked = hours_worked # Количество отработанных часов

    def calculate_salary(self) -> float:
        """
        Реализация расчёта зарплаты для разработчика.
        Зарплата = почасовая ставка * количество отработанных часов.
        """
        return self.hourly_rate * self.hours_worked

    def display(self) -> str:
        """
        Возвращает информацию о разработчике,
        включая количество отработанных часов.
        """
        return f"Developer {self.name} (ID: {self.employee_id}), hours = {self.hours_worked}"

    # Собственный метод разработчика
    def write_code(self, language: str) -> str:
        """
        Метод, специфичный для разработчиков.
        Принимает язык программирования и возвращает строку о написании кода.
        """
        return f"{self.name} кодит на {language}"


# -----------------------------------------------------------------------------
# ТЕСТОВАЯ ФУНКЦИЯ, ДЕМОНСТРИРУЮЩАЯ ПОЛИМОРФИЗМ
# -----------------------------------------------------------------------------
def print_employee_info(emp: Employee) -> None:
    """
    Функция принимает объект, являющийся наследником класса Employee.
    Благодаря полиморфизму мы можем передавать сюда как Manager, так и Developer.
    Функция вызывает методы display() и calculate_salary(),
    которые будут выполнены в соответствии с реальным типом объекта.
    Также мы используем isinstance() для проверки типа и вызова
    специфических методов, если они есть.

    Аргументы:
        emp (Employee): объект-наследник Employee.
    """
    # print(emp) неявно вызывает __str__, который мы переопределили в каждом классе
    print(emp)

    # calculate_salary() вызывается полиморфно — версия метода зависит от типа emp
    print(f"Salary: {emp.calculate_salary():.2f}")

    # Проверяем, является ли emp экземпляром Manager
    if isinstance(emp, Manager):
        # Если да, то можем вызвать метод, специфичный для менеджера
        print(emp.conduct_meeting())
    # Проверяем, является ли emp экземпляром Developer
    elif isinstance(emp, Developer):
        # Если да, вызываем метод разработчика
        print(emp.write_code("Python"))

    print("-" * 40)  # Разделитель для красоты вывода


# -----------------------------------------------------------------------------
# ГЛАВНАЯ ЧАСТЬ ПРОГРАММЫ (запускается только при прямом исполнении файла)
# -----------------------------------------------------------------------------
if __name__ == "__main__":
    """
    Блок, который выполняется, если скрипт запущен напрямую,
    а не импортирован как модуль.
    Здесь мы создаём объекты, демонстрируем работу методов,
    а также показываем полиморфизм.
    """

    # Создаём объект менеджера
    mgr = Manager("Катя", 101, 92000, 2505)

    # Создаём объект разработчика
    dev = Developer("Петя", 102, 850, 160)

    # ===== Прямой вызов методов (без полиморфизма) =====
    print("=== Direct calls ===")
    print(mgr.display())                 # Вывод информации о менеджере
    print(f"Salary: {mgr.calculate_salary():.2f}")  # Расчёт зарплаты
    print(mgr.conduct_meeting())         # Специфический метод
    print()                              # Пустая строка для разделения

    print(dev.display())                 # Вывод информации о разработчике
    print(f"Salary: {dev.calculate_salary():.2f}")
    print(dev.write_code("C++"))         # Специфический метод разработчика
    print()

    # ===== Полиморфное использование через функцию =====
    print("=== Polymorphism via function ===")
    # Передаём разные объекты, но функция работает с ними единообразно
    print_employee_info(mgr)
    print_employee_info(dev)

    # ===== Работа со списком объектов разных типов =====
    print("=== Processing a list of employees ===")
    # Список может содержать объекты любых наследников Employee
    employees = [mgr, dev]
    for e in employees:
        # Полиморфный вызов: для каждого объекта вызывается своя версия метода
        print(f"{e.name} зарабатывает {e.calculate_salary():.2f}")

        # Дополнительно проверяем тип, чтобы вывести специфическую информацию
        if isinstance(e, Manager):
            print(f"  (Manager) {e.conduct_meeting()}")
        elif isinstance(e, Developer):
            print(f"  (Developer) {e.write_code('JavaScript')}")
        print()  # Пустая строка для разделения

    # ===== Демонстрация разницы между str() и __str__ =====
    print("=== Difference between str() and __str__ ===")
    # str(obj) вызывает метод obj.__str__()
    print("str(mgr):", str(mgr))
    # Можно вызвать напрямую метод __str__ (но так делать не принято)
    print("mgr.__str__():", mgr.__str__())
    # Если мы не переопределили __str__, то str() использует __repr__,
    # но в нашем случае мы переопределили __str__ во всех классах.
    print("(Оба вызова дают одинаковый результат, так как __str__ переопределён.)")